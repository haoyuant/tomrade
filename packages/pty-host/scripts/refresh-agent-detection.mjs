/*
 * Refreshes the pty host's copy of herdr's agent detection manifests (herdrdev/herdr, Apache-2.0), the rules it reads
 * an agent's idle / working / blocked off its pane's screen with:
 *
 *   pnpm --filter @tomradex/pty-host refresh-agent-detection [<herdr commit>]
 *
 * Without a commit it takes herdr's default branch as it is now. It writes herdr's manifests, LICENSE and the commit
 * they came from into agent-detection/, and src/manifests.ts from them. Then: review the diff (a pattern herdr's
 * linear-time engine runs well can backtrack in JavaScript's), run `pnpm --filter @tomradex/pty-host bench:detection`
 * and the pty host's tests (tests/detection.test.ts holds the screens herdr reads), and commit.
 *
 * A copy, not herdr's live feed: the host runs offline and outlives the app, and each update is checked here first.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "smol-toml";

const REPO = "herdrdev/herdr";
const SOURCE = "distribution/agent-detection";
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "agent-detection");

async function get(url) {
  const res = await fetch(url, { headers: { "user-agent": "tomrade-refresh-agent-detection" } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

/** The commit a ref names on herdr's repository (its default branch without one), as git reads it. */
function commitOf(ref) {
  if (/^[0-9a-f]{40}$/.test(ref ?? "")) return ref;
  const out = execFileSync("git", ["ls-remote", `https://github.com/${REPO}.git`, ref ?? "HEAD"], { encoding: "utf8" });
  const sha = out.split(/\s/, 1)[0];
  if (!/^[0-9a-f]{40}$/.test(sha)) throw new Error(`herdr has no ${ref ?? "HEAD"}`);
  return sha;
}

/** The TypeScript the host runs: every manifest as herdr wrote it, by file, a rule a line. */
function generated(manifests, sha) {
  const entry = ([file, { rules, ...head }]) => `  ${JSON.stringify(file)}: ${JSON.stringify(head).slice(0, -1)},"rules":[\n${rules.map((r) => `    ${JSON.stringify(r)}`).join(",\n")}\n  ]}`;
  return [
    "// Generated by scripts/refresh-agent-detection.mjs from agent-detection/*.toml (herdr's, Apache-2.0); do not edit.",
    'import type { AgentManifest } from "./detection.js";',
    "",
    "/** The herdr commit the manifests came from. */",
    `export const HERDR_COMMIT = ${JSON.stringify(sha)};`,
    "",
    "/** herdr's agent detection manifests, by file. */",
    `export const MANIFESTS: Record<string, AgentManifest> = {\n${Object.entries(manifests).map(entry).join(",\n")}\n};`,
    ""
  ].join("\n");
}

async function main() {
  const sha = commitOf(process.argv[2]);
  const raw = (file) => get(`https://raw.githubusercontent.com/${REPO}/${sha}/${file}`);
  const index = await raw(`${SOURCE}/index.toml`);
  const files = parse(index).agents.map((a) => a.path).sort();
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "index.toml"), index);
  const manifests = {};
  for (const file of files) {
    if (!/^[a-z0-9-]+\.toml$/.test(file)) throw new Error(`unexpected manifest path ${file}`);
    const text = await raw(`${SOURCE}/${file}`);
    fs.writeFileSync(path.join(dir, file), text);
    manifests[file] = parse(text);
  }
  fs.writeFileSync(path.join(dir, "LICENSE"), await raw("LICENSE"));
  fs.writeFileSync(
    path.join(dir, "NOTICE"),
    [
      "Agent detection manifests from herdr (https://github.com/herdrdev/herdr),",
      "licensed under the Apache License, Version 2.0 (see LICENSE in this folder).",
      "",
      `Copied unmodified from ${SOURCE}/ at commit ${sha}.`,
      "Refresh with: pnpm --filter @tomradex/pty-host refresh-agent-detection [<commit>]",
      ""
    ].join("\n")
  );
  fs.writeFileSync(path.join(root, "src/manifests.ts"), generated(manifests, sha));
  console.log(`herdr ${sha.slice(0, 12)}: ${files.length} manifests`);
}

await main();
